const assert=require('node:assert/strict');
const {reconcileAfterSave}=require('../src/saveReconciliation');
const source={id:null,bride:'Asha',groom:'Dev',message:'Initial',designId:'rajwada'};
const saved={...source,id:'saved-123',createdAt:'2026-11-20T04:00:00.000Z'};
const latest={...source,message:'Typed while saving',venue:'New venue'};
const same=reconcileAfterSave(saved,source,false);
assert.equal(same.hasUnsavedEdits,false);
assert.deepEqual(same.invite,saved);
const merged=reconcileAfterSave(saved,latest,true);
assert.equal(merged.hasUnsavedEdits,true);
assert.equal(merged.invite.id,'saved-123');
assert.equal(merged.invite.createdAt,saved.createdAt);
assert.equal(merged.invite.message,'Typed while saving');
assert.equal(merged.invite.venue,'New venue');
assert.equal(saved.message,'Initial');
assert.equal(source.id,null);
assert.equal(latest.id,null);
const existing={...source,id:'old-42',createdAt:'2026-11-19T00:00:00Z'};
const existingSaved={...existing,updatedAt:'2026-11-20T00:00:00Z'};
const changed=reconcileAfterSave(existingSaved,{...existing,message:'new edit'},true);
assert.equal(changed.invite.id,'old-42');
assert.equal(changed.invite.message,'new edit');
assert.equal(changed.invite.createdAt,existing.createdAt);
assert.throws(()=>reconcileAfterSave({...saved,id:null},latest,true),/Invalid completed/);
assert.throws(()=>reconcileAfterSave(saved,null,true),/Invalid live/);
console.log('PASS: latest typed edits survive async Save, original saved snapshot stays intact, ID retained, unsaved flag remains true');
